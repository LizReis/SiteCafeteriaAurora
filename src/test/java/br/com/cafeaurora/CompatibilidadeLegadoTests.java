package br.com.cafeaurora;

import br.com.cafeaurora.repository.*;
import br.com.cafeaurora.service.AdminPedidoService;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.builder.SpringApplicationBuilder;
import java.nio.file.Path;
import java.sql.DriverManager;
import java.math.BigDecimal;
import static org.junit.jupiter.api.Assertions.*;

class CompatibilidadeLegadoTests {
    @TempDir Path temporario;

    @Test void atualizaEsquemaAntigoEmBancoTemporarioSemPerderHistoricoEmDoisInicios() throws Exception {
        String url="jdbc:h2:file:"+temporario.resolve("legado").toAbsolutePath();
        // Esquema anterior às colunas de classificação, cotação e acompanhamento.
        try(var c=DriverManager.getConnection(url,"sa",""); var s=c.createStatement()) {
            s.execute("create table categorias(id bigint generated by default as identity primary key,nome varchar(80) not null unique,descricao varchar(255),ativa boolean not null)");
            s.execute("create table produtos(id bigint generated by default as identity primary key,nome varchar(120) not null,descricao varchar(1000),preco numeric(10,2) not null,imagem_url varchar(500),ativo boolean not null,disponivel boolean not null,categoria_id bigint not null references categorias(id))");
            s.execute("create table pedidos(id bigint generated by default as identity primary key,nome_cliente varchar(120) not null,telefone_cliente varchar(30),endereco_entrega varchar(500),observacoes varchar(1000),tipo_atendimento varchar(25) not null,status varchar(25) not null,forma_pagamento varchar(30) not null,status_pagamento varchar(20) not null,total numeric(10,2) not null,criado_em timestamp with time zone not null)");
            s.execute("create table itens_pedido(id bigint generated by default as identity primary key,pedido_id bigint not null references pedidos(id),produto_id bigint not null references produtos(id),nome_produto varchar(120) not null,quantidade integer not null,preco_unitario numeric(10,2) not null)");
            s.execute("insert into categorias values(1,'Doces e Salgados','Preservar',false)");
            s.execute("insert into produtos values(1,'Produto antigo','Editado',77.25,null,false,false,1)");
            s.execute("insert into pedidos values(1,'Cliente fictício','11999999999',null,null,'RETIRADA','RECEBIDO','DINHEIRO','PENDENTE',10.00,CURRENT_TIMESTAMP)");
            s.execute("insert into itens_pedido values(1,1,1,'Nome histórico',1,10.00)");
        }
        for(int i=0;i<2;i++) {
            try(var app=new SpringApplicationBuilder(CafeAuroraApplication.class).run(
                "--spring.datasource.url="+url,"--spring.jpa.hibernate.ddl-auto=update",
                "--spring.profiles.active=dev","--server.port=0","--spring.main.banner-mode=off",
                "--spring.devtools.restart.enabled=false","--spring.devtools.livereload.enabled=false",
                "--cafe.admin.username=admin","--cafe.admin.password=senha-exclusiva-para-testes")) {
                var produtos=app.getBean(ProdutoRepository.class);
                var categorias=app.getBean(CategoriaRepository.class);
                assertEquals(1,produtos.count());assertEquals(1,categorias.count());
                assertFalse(produtos.findById(1L).orElseThrow().isAtivo());
                assertEquals(new BigDecimal("77.25"),produtos.findById(1L).orElseThrow().getPreco());
                var categoria=categorias.findById(1L).orElseThrow();
                assertFalse(categoria.isAtiva());assertEquals("Preservar",categoria.getDescricao());
                assertEquals(br.com.cafeaurora.enums.TipoCardapio.COMIDAS,categoria.getTipoCardapio());
                var p=app.getBean(AdminPedidoService.class).detalhar(1L);
                assertEquals(new BigDecimal("10.00"),p.total());
                assertNull(p.subtotal());assertNull(p.taxaEntrega());assertNull(p.email());
                assertEquals("Nome histórico",p.itens().getFirst().nome());
                assertEquals(new BigDecimal("10.00"),p.itens().getFirst().precoUnitario());
            }
        }
    }
}
